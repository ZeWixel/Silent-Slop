    public static int width(String s)
    {
        return s.length() * W;
    }

    /** Draws at 1x with a 1 px drop shadow, into an RGB565 framebuffer. */
    public static void draw(Fb fb, String s, int x, int y, int color, int shadow)
    {
        if (s == null) return;
        if (shadow >= 0) drawRaw(fb, s, x + 1, y + 1, shadow);
        drawRaw(fb, s, x, y, color);
    }

    public static void drawRaw(Fb fb, String s, int x, int y, int color)
    {
        short c = (short) color;
        short[] p = fb.px;
        int W = fb.w, H = fb.h;
        int n = s.length();
        for (int i = 0; i < n; i++)
        {
            int ch = s.charAt(i);
            if (ch == '\n') continue;
            if (ch < 32 || ch > 127) ch = '?';
            int gx = x + i * 6;
            if (gx + W < 0)
                continue;
            if (gx >= W)
                break;
            int o = (ch & 0x7F) * 8;
            for (int row = 0; row < 7; row++)
            {
                int gy = y + row;
                if (gy < 0 || gy >= H) continue;
                int bits = G[o + row] & 0xFF;
                if (bits == 0) continue;
                int base = gy * W + gx;
                for (int b = 0; b < 6; b++)
                {
                    if ((bits & (0x20 >> b)) == 0) continue;
                    int px = gx + b;
                    if (px < 0 || px >= W) continue;
                    p[base + b] = c;
                }
            }
        }
    }

    public static int glyph(char c)
    {
        if (c < 32 || c > 127) c = '?';
        int o = (c & 0x7F) * 6;
        int v = 0;
        for (int i = 0; i < 6; i++) v = (v << 8) | (G[o + i] & 0xFF);
        return v;
    }
